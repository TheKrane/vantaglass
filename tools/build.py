#!/usr/bin/env python3
"""Build the dark Vantaglass theme. Python standard library only."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Vantablack Color palette.
PALETTES = {'vantaglass': {'mode': 'dark',
              'accent': '#8d8d8d',
              'selection': '#1a1a1a',
              'muted': '#7a7a7a',
              'background': '#000000',
              'dark_background': '#090909',
              'darker_background': '#070707',
              'lighter_background': '#1a1a1a',
              'foreground': '#ffffff',
              'dark_foreground': '#505050',
              'light_foreground': '#ececec',
              'bright_foreground': '#ffffff',
              'red': '#f38ba8',
              'yellow': '#f9e2af',
              'orange': '#fab387',
              'green': '#a6e3a1',
              'cyan': '#94e2d5',
              'blue': '#89b4fa',
              'magenta': '#cba6f7',
              'brown': '#b68b76',
              'bright_red': '#f38ba8',
              'bright_yellow': '#f9e2af',
              'bright_green': '#a6e3a1',
              'bright_cyan': '#94e2d5',
              'bright_blue': '#89b4fa',
              'bright_magenta': '#cba6f7'}}

def shell(p):
    surface = '#000000'
    border = '#FFFFFF'
    alpha = lambda n: n
    sections = {
        'vantaglass': {'identity': 'vantaglass', 'secondary-text-alpha': .63},
        'bar': {'background': '#000000', 'background-alpha': alpha(0), 'text': '#FFFFFF', 'active': '#FFFFFF', 'size-horizontal': 28, 'size-vertical': 32, 'scale-with-font': False},
        'hyprland': {'active-border': '#FFFFFF30', 'active-border-foreground': p['foreground']},
        'font': {'base-size': 12},
        'spacing': {'scale': 1.0, 'scale-with-font': False, 'control-height': 28, 'popup-row-height': 28, 'control-gap': 6, 'control-padding-x': 10, 'control-padding-y': 5, 'input-padding-y': 7, 'row-gap': 6, 'row-padding-x': 10, 'panel-gap': 12, 'panel-padding': 16, 'popup-padding': 14, 'label-gap': 4},
        'controls': {'normal-color': p['foreground'], 'normal-fill-alpha': .035, 'normal-border-width': 0, 'normal-border-alpha': 0, 'hover-cursor-color': p['foreground'], 'hover-cursor-fill-alpha': .075, 'hover-cursor-border-width': 1, 'hover-cursor-border-alpha': .30, 'focus-color': p['foreground'], 'focus-fill-alpha': .05, 'focus-border': p['accent'], 'focus-border-width': 2, 'focus-border-alpha': .8, 'selected-color': p['foreground'], 'selected-fill-alpha': .12, 'selected-border-width': 1, 'selected-border-alpha': .18, 'pressed-fill-alpha': .14, 'selection-fill-alpha': .22},
    }
    for name in ['popups', 'tooltip', 'notifications', 'launcher', 'menu', 'polkit', 'lock']:
        sections[name] = {'background': surface, 'background-alpha': alpha(.96 if name in ['polkit', 'tooltip', 'lock'] else .70), 'text': p['foreground'], 'border': border, 'border-alpha': .14, 'border-width': 1}
    for name in ['popups', 'menu', 'launcher', 'notifications']:
        sections[name].update({'border': '#FFFFFF52 #FFFFFF0D #00000032 110deg', 'border-alpha': 1.0})
    sections['notifications']['countdown'] = p['accent']
    for name in ['launcher', 'menu']:
        sections[name].update({'scrim': '#000000', 'scrim-alpha': .08, 'selected-background': '#000000', 'selected-background-alpha': .09, 'selected-text': p['foreground'], 'selected-border': p['foreground'], 'selected-border-alpha': .30, 'selected-border-width': 1})
    sections['polkit'].update({'text-error': p['red'], 'border-error': p['red'], 'accent': p['accent'], 'scrim': '#000000', 'scrim-alpha': .35})
    sections['lock'].update({'placeholder': p['muted'], 'text-error': p['red'], 'border-active': p['accent'], 'border-error': p['red'], 'selection': p['accent'], 'selection-alpha': .25})
    sections['image-picker'] = {'text': p['foreground'], 'selected-border': p['accent'], 'selected-border-alpha': 1.0, 'unselected-border': p['foreground'], 'unselected-border-alpha': .25}
    def literal(v):
        if isinstance(v, bool): return str(v).lower()
        if isinstance(v, str): return '"'+v+'"'
        return str(v)
    return '# Vantaglass · generated by tools/build.py\n\n'+'\n\n'.join('['+section+']\n'+'\n'.join(k+' = '+literal(v) for k,v in values.items()) for section,values in sections.items())+'\n'

def build():
    for name, p in PALETTES.items():
        dest = ROOT/'themes'/'vantaglass'
        (dest/'backgrounds').mkdir(parents=True, exist_ok=True)
        values = dict(p)
        for color in ['red','yellow','green','cyan','blue','magenta']: values['bright_'+color] = p[color]
        active_border='#FFFFFF30'
        values.update(selection_background=p['selection'], selection_foreground=p['foreground'], hyprland_active_border=active_border, hyprland_inactive_border='#FFFFFF16')
        (dest/'colors.toml').write_text('\n'.join(k+' = "'+v+'"' for k,v in values.items())+'\n')
        (dest/'shell.toml').write_text(shell(p))
        (dest/'icons.theme').write_text('Yaru-blue\n')
        # The photograph is a checked-in asset, not regenerated artwork.
        wallpaper = dest/'backgrounds/01-misty-forest.jpg'
        if not wallpaper.is_file(): raise RuntimeError('Bundled forest wallpaper is missing')
        # Theme-local geometry is restored naturally when another theme is applied.
        (dest/'hyprland.lua').write_text('''-- Vantaglass geometry; user overrides load afterward.
hl.config({
  general = { gaps_in = 5, gaps_out = 12, border_size = 1,
    col = { active_border = "%s", inactive_border = "%s" } },
  decoration = { rounding = 18, rounding_power = 2.0,
    shadow = { enabled = true, range = 30, render_power = 3, color = "rgba(00000032)" },
    blur = { enabled = true, size = 6, passes = 2, new_optimizations = true,
      xray = false, contrast = 1.0, brightness = 1.0, noise = 0.008, vibrancy = 0.12, popups = true } },
  group = { col = { border_active = "%s", border_inactive = "%s" } },
})
for _, ns in ipairs({ "^omarchy-bar$", "^omarchy-menu$", "^omarchy-notifications$", "^omarchy-keyboard-panel$" }) do
  hl.layer_rule({ match = { namespace = ns }, blur = true, ignore_alpha = 0.35 })
end
''' % (active_border,values['hyprland_inactive_border'],active_border,values['hyprland_inactive_border']))
        print(dest.name)

if __name__ == '__main__': build()
